"use client";

import { Scale } from "lucide-react";
import { useId } from "react";
import { Badge, Callout, ErrorState, Input, NumberField, Skeleton } from "@/components/ui";
import type { InitialState, JsonSchema, RuleTemplate, SpecRule } from "@/lib/api";
import { cn } from "@/lib/cn";
import { formatSyn } from "@/lib/format";
import { UpdatingNote } from "./bits";
import {
  DEFAULT_ALLOWED_MERCHANTS,
  MAX_RULES,
  PRIVILEGED_TOOLS,
  paramErrors,
  paramKind,
  type ParamValue,
  type RuleDraft,
} from "./draft";

export interface PreviewView {
  /** Rules of the latest backend preview (may be from a slightly older request while updating). */
  rules: SpecRule[] | undefined;
  initialState: InitialState | undefined;
  /** The preview matches the current draft. */
  fresh: boolean;
  error: unknown;
  /** No preview has been requested yet (draft not previewable). */
  idle: boolean;
}

export interface StepRulesProps {
  templates: RuleTemplate[];
  getRule: (template: RuleTemplate) => RuleDraft;
  onRuleChange: (templateId: string, next: RuleDraft) => void;
  ruleIdFor: (templateId: string) => string | null;
  preview: PreviewView;
}

/** Step 2: pick rule templates and their parameters; statements come from the backend. */
export function StepRules({ templates, getRule, onRuleChange, ruleIdFor, preview }: StepRulesProps) {
  const selectedCount = templates.filter((t) => getRule(t).enabled).length;
  return (
    <div className="space-y-4">
      <Callout tone="neutral" icon={<Scale />} title="Only explicit rule templates can be adjudicated">
        Each template is a deterministic check over the ledger of a replay in the synthetic marketplace. A promise written in
        natural language cannot be checked mechanically, so it cannot be offered here. The statement shown under each rule is
        generated by the backend from the template and your parameters; it is exactly what the checker decides.
      </Callout>

      <div className="flex flex-wrap items-center justify-between gap-2 text-sm">
        <p className={cn(selectedCount === 0 || selectedCount > MAX_RULES ? "text-warn" : "text-muted")}>
          <span className="tabular font-medium text-fg">{selectedCount}</span> of {templates.length} templates selected
          {selectedCount === 0 ? " - choose at least one" : ""}
          {selectedCount > MAX_RULES ? ` - a spec holds at most ${MAX_RULES} rules` : ""}
        </p>
        <UpdatingNote show={!preview.fresh && !preview.idle && !preview.error} />
      </div>

      {preview.error ? <ErrorState compact error={preview.error} title="The backend rejected the preview" /> : null}

      <ul className="space-y-3">
        {templates.map((t) => (
          <RuleCard
            key={t.id}
            template={t}
            rule={getRule(t)}
            ruleId={ruleIdFor(t.id)}
            onChange={(next) => onRuleChange(t.id, next)}
            statement={preview.rules?.find((r) => r.template === t.id)}
            preview={preview}
          />
        ))}
      </ul>
    </div>
  );
}

function RuleCard({
  template: t,
  rule,
  ruleId,
  onChange,
  statement,
  preview,
}: {
  template: RuleTemplate;
  rule: RuleDraft;
  ruleId: string | null;
  onChange: (next: RuleDraft) => void;
  statement: SpecRule | undefined;
  preview: PreviewView;
}) {
  const id = useId();
  const errors = paramErrors(t, rule);
  const hasParamErrors = Object.keys(errors).length > 0;
  const params = Object.entries(t.params_schema.properties ?? {});
  const required = new Set(t.params_schema.required ?? []);
  const setParam = (name: string, value: ParamValue) => onChange({ ...rule, params: { ...rule.params, [name]: value } });

  return (
    <li
      className={cn(
        "min-w-0 rounded-lg border bg-surface",
        rule.enabled ? "border-line-strong" : "border-line",
      )}
    >
      <div className="flex flex-wrap items-start gap-x-3 gap-y-2 px-4 py-3 sm:px-5">
        <input
          id={`${id}-on`}
          type="checkbox"
          checked={rule.enabled}
          onChange={(e) => onChange({ ...rule, enabled: e.target.checked })}
          aria-describedby={`${id}-evidence`}
          className="mt-0.5 size-4 shrink-0 accent-[var(--accent)]"
        />
        <div className="min-w-0 flex-1">
          <label htmlFor={`${id}-on`} className="block cursor-pointer text-sm font-semibold text-fg">
            {t.title}
          </label>
          <p className="mt-0.5 font-mono text-xs text-muted">
            {t.id} v{t.version}
          </p>
          <p id={`${id}-evidence`} className="mt-1 text-xs text-muted">
            <span className="font-medium text-fg">Evidence the checker reads:</span> {t.evidence}
          </p>
        </div>
        {rule.enabled && ruleId ? (
          <Badge tone="neutral" size="sm" title="Rule id in the spec">
            {ruleId}
          </Badge>
        ) : (
          <span className="text-xs text-subtle">Not included</span>
        )}
      </div>

      {rule.enabled ? (
        <div className="space-y-3 border-t border-line px-4 py-3 sm:px-5">
          {params.length === 0 ? (
            <p className="text-xs text-muted">No parameters: the rule is fixed by the template.</p>
          ) : (
            <div className="grid gap-4 md:grid-cols-2">
              {params.map(([name, schema]) => (
                <ParamEditor
                  key={name}
                  templateId={t.id}
                  name={name}
                  schema={schema}
                  value={rule.params[name] ?? null}
                  required={required.has(name)}
                  error={errors[name]}
                  onChange={(v) => setParam(name, v)}
                  initialState={preview.initialState}
                />
              ))}
            </div>
          )}

          <div className="rounded-md border border-line bg-inset px-3 py-2">
            <p className="text-xs font-medium text-muted">Statement the checker adjudicates (from the backend preview)</p>
            {hasParamErrors ? (
              <p className="mt-1 text-sm text-warn">Fix the parameters above to see the statement.</p>
            ) : statement && (preview.fresh || !preview.error) ? (
              <p className={cn("mt-1 text-sm text-fg", !preview.fresh && "opacity-70")}>
                {statement.statement}
                {!preview.fresh ? <span className="sr-only"> (updating)</span> : null}
              </p>
            ) : preview.error ? (
              <p className="mt-1 text-sm text-muted">No statement: the preview request failed (see above).</p>
            ) : (
              <Skeleton className="mt-1.5 h-4 w-3/4" />
            )}
          </div>
        </div>
      ) : null}
    </li>
  );
}

function ParamEditor({
  templateId,
  name,
  schema,
  value,
  required,
  error,
  onChange,
  initialState,
}: {
  templateId: string;
  name: string;
  schema: JsonSchema;
  value: ParamValue;
  required: boolean;
  error: string | undefined;
  onChange: (v: ParamValue) => void;
  initialState: InitialState | undefined;
}) {
  const title = typeof schema.title === "string" ? schema.title : name;
  const kind = paramKind(schema);

  if (kind === "integer" || kind === "number") {
    const isBudget = templateId === "spend.cumulative_cap" && name === "budget";
    const min = typeof schema.exclusiveMinimum === "number" ? schema.exclusiveMinimum + (kind === "integer" ? 1 : 0) : schema.minimum;
    return (
      <NumberField
        label={isBudget ? "Budget (SYN, synthetic cents)" : title}
        value={typeof value === "number" ? value : null}
        onChange={onChange}
        integer={kind === "integer"}
        min={typeof min === "number" ? min : undefined}
        max={typeof schema.maximum === "number" ? schema.maximum : undefined}
        unit={isBudget ? "SYN" : undefined}
        required={required}
        error={error}
        hint={
          isBudget && initialState
            ? `The synthetic mandate's own budget is ${formatSyn(initialState.mandate.budget, initialState.currency)}; the synthetic wallet holds ${formatSyn(initialState.wallet.balance, initialState.currency)}.`
            : isBudget
              ? "Integer amount in synthetic cents (SYN)."
              : undefined
        }
      />
    );
  }

  if (kind === "string-list" && templateId === "payee.allowlist" && name === "merchants") {
    const merchants = initialState?.merchants ?? DEFAULT_ALLOWED_MERCHANTS.map((id) => ({ id, name: "" }));
    const mandate = new Set(initialState?.mandate.allowed_merchants ?? DEFAULT_ALLOWED_MERCHANTS);
    return (
      <CheckboxGroup
        legend={title}
        hint="Synthetic merchants from the marketplace fixture. A payment to any merchant not listed violates the rule."
        error={error}
        options={merchants.map((m) => ({
          value: m.id,
          label: m.name ? `${m.name}` : m.id,
          detail: `${m.id}${mandate.has(m.id) ? "" : " - not approved in the principal's mandate"}`,
        }))}
        value={Array.isArray(value) ? value : []}
        onChange={onChange}
      />
    );
  }

  if (kind === "string-list" && templateId === "agent.no_privileged_calls" && name === "tools") {
    const list = Array.isArray(value) ? value : [];
    const options = Array.from(new Set([...PRIVILEGED_TOOLS, ...list]));
    return (
      <CheckboxGroup
        legend={title}
        hint="Privileged operations of the synthetic market (principal only). Any attempt is recorded, even though the market refuses it."
        error={error}
        options={options.map((tool) => ({ value: tool, label: tool, mono: true }))}
        value={list}
        onChange={onChange}
      />
    );
  }

  if (kind === "string-list") {
    const list = Array.isArray(value) ? value : [];
    return (
      <Input
        label={title}
        value={list.join(", ")}
        onChange={(e) =>
          onChange(
            e.target.value
              .split(",")
              .map((s) => s.trim())
              .filter(Boolean),
          )
        }
        mono
        required={required}
        error={error}
        hint="Comma-separated values."
      />
    );
  }

  if (kind === "string") {
    return (
      <Input
        label={title}
        value={typeof value === "string" ? value : ""}
        onChange={(e) => onChange(e.target.value)}
        required={required}
        error={error}
      />
    );
  }

  return <p className="text-sm text-warn">{error ?? `${title}: this parameter type cannot be edited here.`}</p>;
}

function CheckboxGroup({
  legend,
  hint,
  error,
  options,
  value,
  onChange,
}: {
  legend: string;
  hint?: string;
  error?: string;
  options: { value: string; label: string; detail?: string; mono?: boolean }[];
  value: string[];
  onChange: (v: string[]) => void;
}) {
  const id = useId();
  const toggle = (v: string, on: boolean) => {
    const next = on ? [...value, v] : value.filter((x) => x !== v);
    // Keep the order of the options so the spec is stable.
    onChange(options.map((o) => o.value).filter((o) => next.includes(o)));
  };
  return (
    <fieldset
      className="min-w-0 space-y-1.5"
      aria-describedby={[hint ? `${id}-hint` : null, error ? `${id}-error` : null].filter(Boolean).join(" ") || undefined}
      aria-invalid={error ? true : undefined}
    >
      <legend className="text-sm font-medium text-fg">{legend}</legend>
      <ul className="space-y-1">
        {options.map((o) => {
          const cid = `${id}-${o.value}`;
          return (
            <li key={o.value} className="flex items-start gap-2">
              <input
                id={cid}
                type="checkbox"
                checked={value.includes(o.value)}
                onChange={(e) => toggle(o.value, e.target.checked)}
                className="mt-0.5 size-4 shrink-0 accent-[var(--accent)]"
              />
              <label htmlFor={cid} className="min-w-0 text-sm">
                <span className={cn("text-fg", o.mono && "font-mono text-xs")}>{o.label}</span>
                {o.detail ? <span className="block font-mono text-xs text-muted">{o.detail}</span> : null}
              </label>
            </li>
          );
        })}
      </ul>
      {hint ? (
        <p id={`${id}-hint`} className="text-xs text-muted">
          {hint}
        </p>
      ) : null}
      {error ? (
        <p id={`${id}-error`} role="alert" className="text-xs font-medium text-bad">
          {error}
        </p>
      ) : null}
    </fieldset>
  );
}
