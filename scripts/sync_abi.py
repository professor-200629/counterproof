"""Copy the compiled contract ABI into the backend and the web app.

Run after `forge build` in contracts/:  uv run --project backend python scripts/sync_abi.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "contracts" / "out" / "CounterProofBounties.sol" / "CounterProofBounties.json"


def main() -> None:
    abi = json.loads(SRC.read_text(encoding="utf-8"))["abi"]
    backend = ROOT / "backend" / "counterproof" / "abi" / "CounterProofBounties.json"
    backend.parent.mkdir(parents=True, exist_ok=True)
    backend.write_text(json.dumps(abi, indent=1), encoding="utf-8")
    web = ROOT / "web" / "src" / "lib" / "abi.ts"
    web.parent.mkdir(parents=True, exist_ok=True)
    web.write_text("// Generated by scripts/sync_abi.py from contracts/out. Do not edit by hand.\n"
                   f"export const counterProofAbi = {json.dumps(abi, indent=1)} as const;\n", encoding="utf-8")
    print(f"wrote {backend.relative_to(ROOT)} and {web.relative_to(ROOT)} ({len(abi)} entries)")


if __name__ == "__main__":
    main()
